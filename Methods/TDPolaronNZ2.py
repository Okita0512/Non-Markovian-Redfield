"""Time-dependent polaron Nakajima-Zwanzig equation for the spin-boson model.

This module implements Eqs. (20)-(27) of

    H. Nuomin, W. Ying, F.-F. Song, P. Zhang, and D. N. Beratan,
    "Sequential construction of a time-dependent polaron transformation"
    (2026 preprint).

The implemented laboratory-frame Hamiltonian is

    H = (bias / 2) sigma_z + tunneling sigma_x
        + sigma_z sum_k g_k (b_k + b_k^dagger)
        + sum_k omega_k b_k^dagger b_k,

with hbar = k_B = 1.  The bias is constant; no Landau-Zener sweep is used.

The reduced equation is propagated in the interaction picture generated by

    H_m(t) = (bias / 2) sigma_z + tunneling * m(t) sigma_x,

where m(t) = exp[-4 F(t)].  The memory integral is evaluated with the
trapezoidal rule and the Volterra equation is advanced by a second-order
Heun predictor-corrector, following the numerical strategy described in the
paper.

Important scope note
--------------------
The time-dependent displacement is exact for the longitudinal spin-boson
Hamiltonian, but the NZ2 closure is second order in the connected transformed
fluctuations.  It is intended for transient dynamics after a factorized
laboratory-frame preparation.  Complete positivity is not guaranteed.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from time import perf_counter
from typing import Callable, Literal, Optional

import numpy as np

try:
    from numba import njit

    NUMBA_AVAILABLE = True
except ImportError:  # pragma: no cover - exercised only without numba
    njit = None
    NUMBA_AVAILABLE = False

Array = np.ndarray
MethodName = Literal["td", "static"]
BackendName = Literal["auto", "numpy", "numba"]


SIGMA_X = np.array([[0.0, 1.0], [1.0, 0.0]], dtype=complex)
SIGMA_Y = np.array([[0.0, -1.0j], [1.0j, 0.0]], dtype=complex)
SIGMA_Z = np.array([[1.0, 0.0], [0.0, -1.0]], dtype=complex)
SIGMA_PLUS = 0.5 * (SIGMA_X + 1.0j * SIGMA_Y)
SIGMA_MINUS = 0.5 * (SIGMA_X - 1.0j * SIGMA_Y)
IDENTITY_2 = np.eye(2, dtype=complex)
CHANNEL_OPERATORS = np.stack((SIGMA_PLUS, SIGMA_MINUS), axis=0)
CHANNEL_SIGNS = np.array([1.0, -1.0])


@dataclass(frozen=True)
class DiscreteHarmonicBath:
    """Discrete representation of a longitudinal harmonic bath.

    Parameters
    ----------
    omega
        Positive mode frequencies omega_k.
    coupling
        Couplings g_k in sigma_z sum_k g_k (b_k + b_k^dagger).
    beta
        Inverse temperature.
    label
        Human-readable bath label used in metadata.
    """

    omega: Array
    coupling: Array
    beta: float
    label: str = "discrete harmonic bath"

    def __post_init__(self) -> None:
        omega = np.asarray(self.omega, dtype=float)
        coupling = np.asarray(self.coupling, dtype=float)
        if omega.ndim != 1 or coupling.ndim != 1:
            raise ValueError("omega and coupling must be one-dimensional arrays")
        if omega.shape != coupling.shape:
            raise ValueError("omega and coupling must have the same shape")
        if np.any(~np.isfinite(omega)) or np.any(~np.isfinite(coupling)):
            raise ValueError("omega and coupling must be finite")
        if np.any(omega <= 0.0):
            raise ValueError("all bath frequencies must be strictly positive")
        if not np.isfinite(self.beta) or self.beta <= 0.0:
            raise ValueError("beta must be finite and strictly positive")

        order = np.argsort(omega)
        object.__setattr__(self, "omega", omega[order])
        object.__setattr__(self, "coupling", coupling[order])

    @property
    def n_modes(self) -> int:
        return int(self.omega.size)

    def _thermal_factor(self) -> Array:
        x = 0.5 * self.beta * self.omega
        # 1/tanh(x) is stable over the frequency ranges used in the benchmark
        # set and avoids overflow in equivalent exponential formulas.
        return 1.0 / np.tanh(x)

    def FG(self, times: Array, chunk_size: int = 512) -> tuple[Array, Array]:
        """Evaluate F(t) and G(t) for arbitrary non-negative times.

        For J(omega) = pi sum_k g_k^2 delta(omega-omega_k),

            F(t) = sum_k (g_k^2/omega_k^2) coth(beta omega_k/2)
                   [1-cos(omega_k t)],
            G(t) = sum_k (g_k^2/omega_k^2) sin(omega_k t).

        Chunking keeps the temporary time-by-mode arrays modest for the
        300-1000 mode legacy benchmark discretizations.
        """

        times = np.asarray(times, dtype=float)
        original_shape = times.shape
        flat = times.reshape(-1)
        if np.any(~np.isfinite(flat)) or np.any(flat < 0.0):
            raise ValueError("times must be finite and non-negative")

        F = np.empty_like(flat)
        G = np.empty_like(flat)
        if self.n_modes == 0:
            F.fill(0.0)
            G.fill(0.0)
            return F.reshape(original_shape), G.reshape(original_shape)

        omega = self.omega
        g2_over_w2 = (self.coupling / omega) ** 2
        weight_F = g2_over_w2 * self._thermal_factor()
        weight_G = g2_over_w2

        for start in range(0, flat.size, chunk_size):
            stop = min(start + chunk_size, flat.size)
            phase = np.outer(flat[start:stop], omega)
            # 1-cos(x) = 2 sin^2(x/2) avoids cancellation at short times.
            F[start:stop] = 2.0 * np.sin(0.5 * phase) ** 2 @ weight_F
            G[start:stop] = np.sin(phase) @ weight_G

        # Enforce the exact origin, which is useful for C(t,0)=0 tests.
        origin = flat == 0.0
        F[origin] = 0.0
        G[origin] = 0.0
        return F.reshape(original_shape), G.reshape(original_shape)

    def log_kappa(self) -> float:
        """Natural logarithm of the static Franck-Condon overlap."""

        return float(
            -2.0
            * np.sum(
                (self.coupling / self.omega) ** 2 * self._thermal_factor()
            )
        )

    def kappa(self) -> float:
        """Static Franck-Condon overlap kappa."""

        exponent = self.log_kappa()
        # Underflow to exactly zero is physically meaningful for an
        # infrared-divergent continuum and harmless numerically.
        return float(np.exp(exponent)) if exponent > -745.0 else 0.0


@dataclass
class PolaronTrajectory:
    """Container for a propagated reduced-density-matrix trajectory.

    ``rho_s`` is the Schrödinger-picture reduced density matrix in the chosen
    TD- or static-polaron frame, after undoing only the mean-system interaction
    picture generated by ``H_m(t)``.  Since the polaron transformation commutes
    with ``sigma_z``, populations and ``sigma_z`` are laboratory-frame
    invariants and can be benchmarked directly.  Off-diagonal laboratory-frame
    coherences require a back-transformation involving bath displacement
    operators and should not be identified with ``rho_s[:, 0, 1]`` without an
    additional approximation.
    """

    times: Array
    rho_s: Array
    rho_interaction: Array
    mean_propagator: Array
    dressing: Array
    F: Array
    G: Array
    method: MethodName
    bias: float
    tunneling: float
    runtime_seconds: float

    @property
    def sigma_z(self) -> Array:
        return np.real(np.einsum("tij,ji->t", self.rho_s, SIGMA_Z))

    @property
    def trace(self) -> Array:
        return np.trace(self.rho_s, axis1=1, axis2=2)

    @property
    def minimum_eigenvalue(self) -> Array:
        hermitian = 0.5 * (self.rho_s + np.swapaxes(self.rho_s.conj(), 1, 2))
        return np.linalg.eigvalsh(hermitian)[:, 0]

    def downsample(self, stride: int) -> "PolaronTrajectory":
        if stride <= 0:
            raise ValueError("stride must be positive")
        sl = slice(None, None, stride)
        return PolaronTrajectory(
            times=self.times[sl],
            rho_s=self.rho_s[sl],
            rho_interaction=self.rho_interaction[sl],
            mean_propagator=self.mean_propagator[sl],
            dressing=self.dressing[sl],
            F=self.F[sl],
            G=self.G[sl],
            method=self.method,
            bias=self.bias,
            tunneling=self.tunneling,
            runtime_seconds=self.runtime_seconds,
        )

    def save_legacy_text(self, path: str | Path, stride: int = 1) -> None:
        """Save in the row-major real/imaginary format used by ``run.py``.

        The diagonal entries and ``sigma_z`` are physical frame-invariant
        populations.  The off-diagonal entries remain polaron-frame
        coherences; see the class docstring.
        """

        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        sampled = self.downsample(stride)
        columns = [sampled.times]
        for row in range(2):
            for col in range(2):
                columns.append(sampled.rho_s[:, row, col].real)
                columns.append(sampled.rho_s[:, row, col].imag)
        np.savetxt(path, np.column_stack(columns), fmt="%.16e", delimiter="\t")

    def save_csv(self, path: str | Path, stride: int = 1) -> None:
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        sampled = self.downsample(stride)
        data = np.column_stack(
            (
                sampled.times,
                sampled.rho_s[:, 0, 0].real,
                sampled.rho_s[:, 0, 0].imag,
                sampled.rho_s[:, 0, 1].real,
                sampled.rho_s[:, 0, 1].imag,
                sampled.rho_s[:, 1, 0].real,
                sampled.rho_s[:, 1, 0].imag,
                sampled.rho_s[:, 1, 1].real,
                sampled.rho_s[:, 1, 1].imag,
                sampled.sigma_z,
                sampled.trace.real,
                sampled.trace.imag,
                sampled.minimum_eigenvalue,
                sampled.dressing,
            )
        )
        header = (
            "time,rho00_re,rho00_im,rho01_re,rho01_im,rho10_re,rho10_im,"
            "rho11_re,rho11_im,sigma_z,trace_re,trace_im,min_eigenvalue,m"
        )
        np.savetxt(path, data, delimiter=",", header=header, comments="", fmt="%.16e")


class _CorrelationProvider:
    """On-grid connected displacement correlation functions."""

    def __init__(
        self,
        F: Array,
        G: Array,
        m: Array,
        method: MethodName,
        kappa: float,
        log_kappa: float,
    ):
        self.F = F
        self.G = G
        self.m = m
        self.method = method
        self.kappa = kappa
        self.log_kappa = log_kappa

    def values(self, i: int, j: Array, q_product: float) -> Array:
        """Return C_{mu,nu}(t_i,t_j) for q_mu q_nu = +/-1.

        The solver only requests j <= i.  The reversed-time correlation in
        the second commutator of Eq. (23) is its complex conjugate.
        """

        j = np.asarray(j, dtype=int)
        lag = i - j
        if np.any(lag < 0):
            raise ValueError("correlation provider expects j <= i")

        if self.method == "td":
            Fi = self.F[i]
            Fj = self.F[j]
            Gi = self.G[i]
            Gj = self.G[j]
            Flag = self.F[lag]
            Glag = self.G[lag]
            E = (
                -4.0 * Fi
                - 4.0 * Fj
                - 4.0 * q_product * (Fi + Fj)
                + 4.0 * q_product * Flag
                + 4.0j * q_product * Glag
                - 4.0j * q_product * (Gi - Gj)
            )
            C = np.exp(E) - self.m[i] * self.m[j]
            # D(0)=I and m(0)=1 imply an exactly vanishing connected
            # correlation whenever the earlier time is zero.
            C = np.where(j == 0, 0.0j, C)
            return C

        lag_F = self.F[lag]
        lag_G = self.G[lag]
        psi = -4.0 * (lag_F + 1.0j * lag_G)
        kappa_squared = self.kappa**2
        if q_product < 0.0:
            return np.exp(psi) - kappa_squared
        # Evaluate kappa^4 exp[-Psi(tau)] in log form.  This avoids
        # 0*inf -> NaN when kappa underflows for infrared-heavy baths.
        return np.exp(4.0 * self.log_kappa - psi) - kappa_squared


def _validate_density_matrix(rho0: Array) -> Array:
    rho0 = np.asarray(rho0, dtype=complex)
    if rho0.shape != (2, 2):
        raise ValueError("rho0 must have shape (2, 2)")
    if not np.all(np.isfinite(rho0)):
        raise ValueError("rho0 must be finite")
    if not np.allclose(rho0, rho0.conj().T, atol=1e-12):
        raise ValueError("rho0 must be Hermitian")
    if not np.isclose(np.trace(rho0), 1.0, atol=1e-12):
        raise ValueError("rho0 must have unit trace")
    return rho0.copy()


def _mean_propagator(
    times: Array,
    bias: float,
    tunneling: float,
    dressing_midpoint: Array,
) -> Array:
    """Second-order midpoint propagation of U_m(t,0)."""

    n_times = times.size
    U = np.empty((n_times, 2, 2), dtype=complex)
    U[0] = IDENTITY_2
    a = 0.5 * bias

    for n in range(n_times - 1):
        dt = times[n + 1] - times[n]
        b = tunneling * dressing_midpoint[n]
        omega_eff = float(np.hypot(a, b))
        H = a * SIGMA_Z + b * SIGMA_X
        if omega_eff < 1e-15:
            step = IDENTITY_2 - 1.0j * dt * H
        else:
            step = (
                np.cos(omega_eff * dt) * IDENTITY_2
                - 1.0j * np.sin(omega_eff * dt) / omega_eff * H
            )
        U[n + 1] = step @ U[n]
    return U


def _interaction_operators(U: Array) -> Array:
    """Return S_mu(t)=U_m^dagger sigma_mu U_m for mu in {+,-}."""

    n_times = U.shape[0]
    operators = np.empty((n_times, 2, 2, 2), dtype=complex)
    U_dag = np.swapaxes(U.conj(), 1, 2)
    for mu in range(2):
        operators[:, mu] = U_dag @ CHANNEL_OPERATORS[mu] @ U
    return operators


def _memory_derivative(
    i: int,
    rho_history: Array,
    S: Array,
    corr: _CorrelationProvider,
    dt: float,
    tunneling: float,
) -> Array:
    """Evaluate the right-hand side of Eq. (23) at grid index i."""

    if i == 0:
        return np.zeros((2, 2), dtype=complex)
    if rho_history.shape[0] != i + 1:
        raise ValueError("rho_history length must equal i+1")

    j = np.arange(i + 1)
    weights = np.ones(i + 1, dtype=float)
    weights[0] = 0.5
    weights[-1] = 0.5

    C_same = corr.values(i, j, q_product=1.0)
    C_cross = corr.values(i, j, q_product=-1.0)
    S_i = S[i]
    derivative_integrand = np.zeros((i + 1, 2, 2), dtype=complex)

    for mu in range(2):
        Smu = S_i[mu]
        for nu in range(2):
            Snu = S[j, nu]
            C_forward = C_same if mu == nu else C_cross
            C_reverse = C_forward.conj()

            Snu_rho = Snu @ rho_history
            commutator_1 = Smu @ Snu_rho - Snu_rho @ Smu

            rho_Snu = rho_history @ Snu
            commutator_2 = rho_Snu @ Smu - Smu @ rho_Snu

            derivative_integrand += (
                C_forward[:, None, None] * commutator_1
                + C_reverse[:, None, None] * commutator_2
            )

    integral = dt * np.einsum("j,jab->ab", weights, derivative_integrand)
    return -(tunneling**2) * integral




if NUMBA_AVAILABLE:

    @njit(cache=True)
    def _matmul2_numba(A: Array, B: Array, out: Array) -> None:
        out[0, 0] = A[0, 0] * B[0, 0] + A[0, 1] * B[1, 0]
        out[0, 1] = A[0, 0] * B[0, 1] + A[0, 1] * B[1, 1]
        out[1, 0] = A[1, 0] * B[0, 0] + A[1, 1] * B[1, 0]
        out[1, 1] = A[1, 0] * B[0, 1] + A[1, 1] * B[1, 1]


    @njit(cache=True)
    def _complex_exp_numba(real_part: float, imag_part: float) -> complex:
        amplitude = np.exp(real_part)
        return amplitude * (np.cos(imag_part) + 1.0j * np.sin(imag_part))


    @njit(cache=True)
    def _correlation_numba(
        i: int,
        j: int,
        q_product: float,
        F: Array,
        G: Array,
        m: Array,
        method_code: int,
        kappa: float,
        log_kappa: float,
    ) -> complex:
        lag = i - j
        if method_code == 0:  # time-dependent polaron
            if j == 0:
                return 0.0j
            Fi = F[i]
            Fj = F[j]
            real_part = (
                -4.0 * Fi
                - 4.0 * Fj
                - 4.0 * q_product * (Fi + Fj)
                + 4.0 * q_product * F[lag]
            )
            imag_part = (
                4.0 * q_product * G[lag]
                - 4.0 * q_product * (G[i] - G[j])
            )
            return _complex_exp_numba(real_part, imag_part) - m[i] * m[j]

        psi_real = -4.0 * F[lag]
        psi_imag = -4.0 * G[lag]
        if q_product < 0.0:
            return _complex_exp_numba(psi_real, psi_imag) - kappa * kappa
        return (
            _complex_exp_numba(
                4.0 * log_kappa - psi_real, -psi_imag
            )
            - kappa * kappa
        )


    @njit(cache=True)
    def _memory_derivative_numba(
        i: int,
        rho_history: Array,
        S: Array,
        F: Array,
        G: Array,
        m: Array,
        method_code: int,
        kappa: float,
        log_kappa: float,
        dt: float,
        tunneling: float,
        out: Array,
    ) -> None:
        out[:, :] = 0.0j
        if i == 0:
            return

        A = np.empty((2, 2), dtype=np.complex128)
        B = np.empty((2, 2), dtype=np.complex128)
        X = np.empty((2, 2), dtype=np.complex128)
        Y = np.empty((2, 2), dtype=np.complex128)
        AX = np.empty((2, 2), dtype=np.complex128)
        XA = np.empty((2, 2), dtype=np.complex128)
        YB = np.empty((2, 2), dtype=np.complex128)
        BY = np.empty((2, 2), dtype=np.complex128)

        Splus_i = S[i, 0]
        Sminus_i = S[i, 1]

        for j in range(i + 1):
            weight = 0.5 if (j == 0 or j == i) else 1.0
            C_same = _correlation_numba(
                i, j, 1.0, F, G, m, method_code, kappa, log_kappa
            )
            C_cross = _correlation_numba(
                i, j, -1.0, F, G, m, method_code, kappa, log_kappa
            )
            rho_j = rho_history[j]

            for nu in range(2):
                if nu == 0:
                    Snu = S[j, 0]
                    # Sum over mu before forming the commutator.
                    A[:, :] = C_same * Splus_i + C_cross * Sminus_i
                    B[:, :] = C_same.conjugate() * Splus_i + C_cross.conjugate() * Sminus_i
                else:
                    Snu = S[j, 1]
                    A[:, :] = C_cross * Splus_i + C_same * Sminus_i
                    B[:, :] = C_cross.conjugate() * Splus_i + C_same.conjugate() * Sminus_i

                _matmul2_numba(Snu, rho_j, X)
                _matmul2_numba(rho_j, Snu, Y)
                _matmul2_numba(A, X, AX)
                _matmul2_numba(X, A, XA)
                _matmul2_numba(Y, B, YB)
                _matmul2_numba(B, Y, BY)

                out[:, :] += weight * (AX - XA + YB - BY)

        out[:, :] *= -(tunneling * tunneling) * dt


    @njit(cache=True)
    def _propagate_interaction_numba(
        rho0: Array,
        S: Array,
        F: Array,
        G: Array,
        m: Array,
        method_code: int,
        kappa: float,
        log_kappa: float,
        dt: float,
        tunneling: float,
        hermitize: bool,
        renormalize_trace: bool,
    ) -> Array:
        n_steps = F.size - 1
        rho = np.empty((n_steps + 1, 2, 2), dtype=np.complex128)
        rho[0] = rho0
        derivative_n = np.zeros((2, 2), dtype=np.complex128)
        derivative_predictor = np.zeros((2, 2), dtype=np.complex128)
        derivative_next = np.zeros((2, 2), dtype=np.complex128)
        _memory_derivative_numba(
            0,
            rho,
            S,
            F,
            G,
            m,
            method_code,
            kappa,
            log_kappa,
            dt,
            tunneling,
            derivative_n,
        )

        for n in range(n_steps):
            rho[n + 1] = rho[n] + dt * derivative_n
            _memory_derivative_numba(
                n + 1,
                rho,
                S,
                F,
                G,
                m,
                method_code,
                kappa,
                log_kappa,
                dt,
                tunneling,
                derivative_predictor,
            )
            rho[n + 1] = rho[n] + 0.5 * dt * (
                derivative_n + derivative_predictor
            )

            if hermitize:
                offdiag = 0.5 * (rho[n + 1, 0, 1] + rho[n + 1, 1, 0].conjugate())
                rho[n + 1, 0, 1] = offdiag
                rho[n + 1, 1, 0] = offdiag.conjugate()
                rho[n + 1, 0, 0] = rho[n + 1, 0, 0].real
                rho[n + 1, 1, 1] = rho[n + 1, 1, 1].real

            if renormalize_trace:
                trace = rho[n + 1, 0, 0] + rho[n + 1, 1, 1]
                rho[n + 1] /= trace

            _memory_derivative_numba(
                n + 1,
                rho,
                S,
                F,
                G,
                m,
                method_code,
                kappa,
                log_kappa,
                dt,
                tunneling,
                derivative_next,
            )
            derivative_n[:, :] = derivative_next

        return rho

def propagate_td_polaron_nz2(
    *,
    bias: float,
    tunneling: float,
    bath: DiscreteHarmonicBath,
    rho0: Array,
    t_max: float,
    dt: float,
    method: MethodName = "td",
    hermitize: bool = True,
    renormalize_trace: bool = False,
    progress: Optional[Callable[[int, int], None]] = None,
    backend: BackendName = "auto",
) -> PolaronTrajectory:
    """Propagate the constant-bias spin-boson TD- or static-polaron NZ2 equation.

    Parameters
    ----------
    bias, tunneling
        Parameters of H_S = (bias/2) sigma_z + tunneling sigma_x.
    bath
        Discrete harmonic bath in the same longitudinal-coupling convention.
    rho0
        Factorized laboratory-frame initial system density matrix.
    t_max, dt
        Final time and uniform time step.  ``t_max/dt`` must be an integer to
        within floating-point tolerance.
    method
        ``"td"`` for Eqs. (20)-(27), or ``"static"`` for Eqs. (28)-(29).
    hermitize
        Apply the same numerical Hermitization used in the paper after each
        Heun corrector step.
    renormalize_trace
        Optional diagnostic stabilization.  Disabled by default because the
        trace error is useful for assessing the numerical calculation.
    progress
        Optional callback ``progress(completed_steps, total_steps)``.  Progress
        callbacks are available with the NumPy backend; the compiled Numba
        backend reports only after completion.
    backend
        ``"auto"`` uses Numba when installed and otherwise falls back to the
        vectorized NumPy implementation.
    """

    if method not in ("td", "static"):
        raise ValueError("method must be 'td' or 'static'")
    if backend not in ("auto", "numpy", "numba"):
        raise ValueError("backend must be 'auto', 'numpy', or 'numba'")
    if backend == "numba" and not NUMBA_AVAILABLE:
        raise ImportError("the numba backend was requested but numba is not installed")
    selected_backend = (
        "numba" if backend == "auto" and NUMBA_AVAILABLE else backend
    )
    if selected_backend == "auto":
        selected_backend = "numpy"

    if not np.isfinite(bias) or not np.isfinite(tunneling):
        raise ValueError("bias and tunneling must be finite")
    if not np.isfinite(t_max) or t_max <= 0.0:
        raise ValueError("t_max must be finite and positive")
    if not np.isfinite(dt) or dt <= 0.0:
        raise ValueError("dt must be finite and positive")

    n_steps_float = t_max / dt
    n_steps = int(round(n_steps_float))
    if not np.isclose(n_steps_float, n_steps, rtol=0.0, atol=1e-10):
        raise ValueError("t_max/dt must be an integer")
    times = np.arange(n_steps + 1, dtype=float) * dt
    rho0 = _validate_density_matrix(rho0)

    start = perf_counter()
    F, G = bath.FG(times)
    log_kappa = bath.log_kappa()
    kappa = bath.kappa()
    if method == "td":
        dressing = np.exp(-4.0 * F)
        mid_times = times[:-1] + 0.5 * dt
        F_mid, _ = bath.FG(mid_times)
        dressing_mid = np.exp(-4.0 * F_mid)
    else:
        dressing = np.full_like(times, kappa)
        dressing_mid = np.full(n_steps, kappa, dtype=float)

    U = _mean_propagator(times, bias, tunneling, dressing_mid)
    S = _interaction_operators(U)
    corr = _CorrelationProvider(
        F=F,
        G=G,
        m=dressing,
        method=method,
        kappa=kappa,
        log_kappa=log_kappa,
    )

    if selected_backend == "numba":
        method_code = 0 if method == "td" else 1
        rho_I = _propagate_interaction_numba(
            rho0,
            S,
            F,
            G,
            dressing,
            method_code,
            kappa,
            log_kappa,
            dt,
            tunneling,
            hermitize,
            renormalize_trace,
        )
        if progress is not None:
            progress(n_steps, n_steps)
    else:
        rho_I = np.empty((n_steps + 1, 2, 2), dtype=complex)
        rho_I[0] = rho0
        derivative_n = _memory_derivative(
            0, rho_I[:1], S, corr, dt=dt, tunneling=tunneling
        )

        for n in range(n_steps):
            predictor = rho_I[n] + dt * derivative_n
            # Temporarily place the predictor in the preallocated history array;
            # this avoids an O(n) concatenate/copy at every time step.
            rho_I[n + 1] = predictor
            derivative_predictor = _memory_derivative(
                n + 1,
                rho_I[: n + 2],
                S,
                corr,
                dt=dt,
                tunneling=tunneling,
            )
            corrected = rho_I[n] + 0.5 * dt * (
                derivative_n + derivative_predictor
            )

            if hermitize:
                corrected = 0.5 * (corrected + corrected.conj().T)
            if renormalize_trace:
                trace = np.trace(corrected)
                if abs(trace) < 1e-14:
                    raise FloatingPointError("density-matrix trace collapsed to zero")
                corrected = corrected / trace

            rho_I[n + 1] = corrected
            derivative_n = _memory_derivative(
                n + 1,
                rho_I[: n + 2],
                S,
                corr,
                dt=dt,
                tunneling=tunneling,
            )
            if progress is not None:
                progress(n + 1, n_steps)

    U_dag = np.swapaxes(U.conj(), 1, 2)
    rho_s = U @ rho_I @ U_dag
    runtime = perf_counter() - start

    return PolaronTrajectory(
        times=times,
        rho_s=rho_s,
        rho_interaction=rho_I,
        mean_propagator=U,
        dressing=dressing,
        F=F,
        G=G,
        method=method,
        bias=float(bias),
        tunneling=float(tunneling),
        runtime_seconds=runtime,
    )


